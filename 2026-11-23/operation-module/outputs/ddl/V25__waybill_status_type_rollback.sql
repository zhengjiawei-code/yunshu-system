-- =============================================================================
-- V25 回滚脚本（仅在家伟批准并执行 V25 后备用，不参与 Flyway）
--
-- 注意：TINYINT UNSIGNED 上限 255，回滚前必须先把 900 归并回业务可接受状态，
--       否则 ALTER 会因现有 900 数据失败。默认归并为 20 已揽收，执行前需业务确认。
-- =============================================================================

UPDATE biz_waybill SET status = 20 WHERE status = 900;

ALTER TABLE biz_waybill
    MODIFY COLUMN status TINYINT UNSIGNED NOT NULL DEFAULT 20
        COMMENT '运单状态：10=待揽收（预开单/导入/接口推送），20=已揽收（默认，开单即20），30=网点装车，40=网点发车，50=分拨到车，60=分拨卸车，70=分拨装车，80=分拨发车，90=末端到车，100=到站待提，110=到站待送，120=到站待转，130=已签收，900=已作废';
